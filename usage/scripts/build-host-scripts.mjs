// Compiles the host-side collectors in lib/host/ to plain JavaScript and writes
// them, as string constants, to lib/generated/host-scripts.ts.
//
// Why: the collectors run on the enrolled host in a bare `node -e`. bb builds
// the plugin bundle minified with esbuild's keepNames, which inserts calls to a
// bundle-level helper inside every function body, so `fn.toString()` of a
// bundled function refers to a helper the host process does not have. Text
// produced here is never seen by bb's bundler as code, only as a string.
//
// Run with `npm run build:host-scripts` after editing lib/host/. The test
// lib/host-scripts.bundle.test.ts fails if the generated file is out of date.
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { transform } from "esbuild";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SCRIPTS = [
  { file: "lib/host/host-json-collector.host.ts", name: "hostJsonCollector", constant: "HOST_JSON_COLLECTOR_SOURCE" },
  { file: "lib/host/cursor-account.host.ts", name: "cursorAccountCollector", constant: "CURSOR_ACCOUNT_COLLECTOR_SOURCE" },
];

export async function renderHostScripts() {
  const parts = [
    "// Generated by scripts/build-host-scripts.mjs from lib/host/. Do not edit.",
    "// Each constant is the source of one async function, run on the enrolled",
    "// host as `(<source>)(input, dependencies)` in a bare node process.",
    "",
  ];
  for (const script of SCRIPTS) {
    const source = await readFile(join(root, script.file), "utf8");
    const declaration = `export async function ${script.name}(`;
    if (source.split(declaration).length !== 2) {
      throw new Error(`${script.file}: expected exactly one \`${declaration}\`.`);
    }
    // Types are stripped and nothing else: no minify, no keepNames, no bundle,
    // so the output refers to no name outside the function. The export keyword
    // goes first, so esbuild emits a bare declaration and no export list.
    const { code } = await transform(source.replace(declaration, `async function ${script.name}(`), {
      loader: "ts", format: "esm", target: "node22",
    });
    const body = code.trim();
    if (!body.startsWith(`async function ${script.name}(`) || !body.endsWith("}")) {
      throw new Error(`${script.file}: the file may hold type imports and \`${declaration}\` only.`);
    }
    // The text must stand on its own in a bare node process.
    new Function(`return (${body});`);
    parts.push(`export const ${script.constant} = ${JSON.stringify(body)};`, "");
  }
  return parts.join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const output = join(root, "lib/generated/host-scripts.ts");
  await writeFile(output, await renderHostScripts());
  console.log(`wrote ${output}`);
}
